const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '../../../docs');
const html = fs.readFileSync(path.join(root, 'war-results-vision.html'), 'utf8');
for (const file of ['war-results-vision.css', 'war-results-vision-engine.js', 'war-results-vision-data.js', 'war-results-vision.js', 'war-result-recognition-core.js']) assert.ok(fs.existsSync(path.join(root, file)), `${file} exists`);
assert.match(html, /war-counter-lab\.css/, 'reuses War Counter Vision styles');
assert.match(html, /type="file"[^>]+multiple/, 'accepts multiple images');
assert.match(html, /image\/png,image\/jpeg/, 'accepts PNG and JPEG');
assert.match(html, /war-results-vision-data\.js/, 'loads local data model');
assert.doesNotMatch(html, /auth-guard|home\.html|navigation/i, 'page has no added gate or navigation');
const engine = fs.readFileSync(path.join(root, 'war-results-vision-engine.js'), 'utf8');
assert.match(engine, /CORE\.extract/, 'uses the existing local OCR core');
assert.match(engine, /createWorker/, 'Tesseract worker runs in browser');
assert.match(engine, /zone-psm7/, 'field crops are read using targeted segmentation');
assert.match(engine, /analyzeField/, 'a single corrected field can be reread');
assert.match(engine, /whole-image-vs-zone-disagreement/, 'contradictory reads remain unresolved');
assert.doesNotMatch(engine, /fetch\(|XMLHttpRequest|gemini|groq|\/api\//i, 'no app-level remote OCR or publishing call');
const app = fs.readFileSync(path.join(root, 'war-results-vision.js'), 'utf8');
assert.match(app, /type="date"/, 'manual war date control exists');
assert.match(app, /sessionStorage/, 'text drafts persist for the tab session');
assert.match(app, /createObjectURL/, 'images remain local browser objects');
const data = fs.readFileSync(path.join(root, 'war-results-vision-data.js'), 'utf8');
assert.match(data, /validated-locally-not-published/, 'local validation does not publish');
console.log('war results vision static integration tests: ok');
