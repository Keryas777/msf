const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '../../../docs');
const html = fs.readFileSync(path.join(root, 'war-results-vision.html'), 'utf8');
for (const file of ['war-results-vision.css', 'war-results-vision-engine.js', 'war-results-identity-engine.js', 'war-results-result-engine.js', 'war-results-vision-data.js', 'war-results-vision.js', 'war-result-recognition-core.js']) assert.ok(fs.existsSync(path.join(root, file)), `${file} exists`);
assert.match(html, /war-counter-lab\.css/, 'reuses War Counter Vision styles');
assert.match(html, /type="file"[^>]+multiple/, 'accepts multiple images');
assert.match(html, /image\/png,image\/jpeg/, 'accepts PNG and JPEG');
assert.match(html, /war-results-vision-data\.js/, 'loads local data model');
assert.ok(html.indexOf('war-results-identity-engine.js') < html.indexOf('war-results-vision-engine.js'), 'identity engine loads before the adapter');
assert.ok(html.indexOf('war-results-result-engine.js') < html.indexOf('war-results-vision-engine.js'), 'result engine loads before the adapter');
assert.doesNotMatch(html, /auth-guard|home\.html|navigation/i, 'page has no added gate or navigation');
const engine = fs.readFileSync(path.join(root, 'war-results-vision-engine.js'), 'utf8');
assert.match(engine, /CORE\.extract/, 'uses the existing local OCR core');
assert.match(engine, /createWorker/, 'Tesseract worker runs in browser');
assert.match(engine, /zone-psm7/, 'field crops are read using targeted segmentation');
assert.match(engine, /analyzeField/, 'a single corrected field can be reread');
assert.doesNotMatch(engine, /fetch\(|XMLHttpRequest|gemini|groq|\/api\//i, 'no app-level remote OCR or publishing call');
assert.match(engine, /WarResultsIdentityEngine/, 'identity engine is integrated');
assert.match(engine, /WarResultsResultEngine/, 'result engine is integrated');
assert.match(engine, /paddingByGlyphHeight: 0\.18/, 'production trophy margin stays at 18%');
const recognitionCore = fs.readFileSync(path.join(root, 'war-result-recognition-core.js'), 'utf8');
assert.doesNotMatch(recognitionCore, /knownLocal|\["Zeus", "Dionysos", "Poseidon"/, 'identity names are not forced to a closed alliance list');
const identityEngine = fs.readFileSync(path.join(root, 'war-results-identity-engine.js'), 'utf8');
assert.match(identityEngine, /ocr-read-disagreement/, 'contradictory identity reads remain unresolved');
assert.match(identityEngine, /richName/, 'text presentation has the compatible richName shape');
const resultEngine = fs.readFileSync(path.join(root, 'war-results-result-engine.js'), 'utf8');
assert.match(resultEngine, /targeted-title-ocr-fallback/, 'result OCR is only a named fallback path');
const app = fs.readFileSync(path.join(root, 'war-results-vision.js'), 'utf8');
assert.match(app, /type="date"/, 'manual war date control exists');
assert.match(app, /sessionStorage/, 'text drafts persist for the tab session');
assert.match(app, /createObjectURL/, 'images remain local browser objects');
const data = fs.readFileSync(path.join(root, 'war-results-vision-data.js'), 'utf8');
assert.match(data, /validated-locally-not-published/, 'local validation does not publish');
console.log('war results vision static integration tests: ok');
